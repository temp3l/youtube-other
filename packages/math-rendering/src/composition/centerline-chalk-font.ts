export function centerlineGlyphDefinition(
  grapheme: string
): CenterlineGlyphDefinition {
  const direct = symbols[grapheme] ?? lower[grapheme] ?? upper[grapheme];
  if (direct) return direct;
  const normalized = grapheme.normalize("NFD");
  const base = normalized[0] ?? grapheme;
  const baseDefinition = symbols[base] ?? lower[base] ?? upper[base];
  if (!baseDefinition) return symbols["?"]!;
  const marks = [...normalized]
    .slice(1)
    .flatMap((mark) => combiningMarks[mark] ?? []);
  return {
    advanceWidth: baseDefinition.advanceWidth,
    paths: [...baseDefinition.paths, ...marks],
  };
}
