export interface CenterlinePoint {
  readonly x: number;
  readonly y: number;
}

export interface CenterlineGlyphDefinition {
  readonly advanceWidth: number;
  readonly paths: readonly (readonly CenterlinePoint[])[];
}

function parsePath(value: string): readonly CenterlinePoint[] {
  return value.split(" ").map((pair) => {
    const [x, y] = pair.split(",").map(Number);
    if (x === undefined || y === undefined || !Number.isFinite(x + y))
      throw new Error(`Invalid centerline glyph point: ${pair}`);
    return { x, y };
  });
}

function glyph(
  advanceWidth: number,
  ...paths: readonly string[]
): CenterlineGlyphDefinition {
  return { advanceWidth, paths: paths.map(parsePath) };
}

